// Generate finite typed native expectations from the production JS register.
import { writeFile, readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import { merge } from '../../js/src/sync/register.js';
import { fixtures } from './native-register-cases.mjs';
import { format } from 'prettier';

let output = `// Generated by experiments/issue-56/native-register-vectors.mjs.
// Expected records come from the production JavaScript implementation.
use meta_sovereign_core::{AssignmentStamp, Link, VectorClock, try_merge};
// Reuse the existing std-only reader in this unpublished workspace's tests.
#[path = "../../meta-sovereign-server/src/json.rs"]
mod json;
use json::Value;

fn clock(value: &Value) -> VectorClock {
    value.as_object().unwrap().iter().map(|(k,v)| {
        let Value::Number(n) = v else { panic!("fixture counter") };
        (k.clone(), *n as u64)
    }).collect()
}
fn record(value: &Value) -> Link {
    let mut link = Link::new(value.get("id").unwrap().as_str().unwrap(),
        value.get("tokens").unwrap().as_array().unwrap().iter().map(|t| t.as_str().unwrap()));
    link.children = value.get("children").unwrap().as_array().unwrap().iter()
        .map(|c| c.as_str().unwrap().to_owned()).collect();
    link.vc = clock(value.get("vc").unwrap());
    link.version = value.get("version").map(|v| v.as_str().unwrap().to_owned());
    link.sync_stamp = value.get("__msSyncStamp").map(|s| AssignmentStamp {
        clock: clock(s.get("clock").unwrap()), context: clock(s.get("context").unwrap()),
    });
    link
}
fn fixture(name: &str) {
    let values = json::parse(include_str!("fixtures/sync-register.json"))
        .unwrap_or_else(|error| panic!("invalid fixture: {}", error.0));
    let item = values.as_array().unwrap().iter()
        .find(|v| v.get("name").unwrap().as_str() == Some(name)).unwrap();
    let records: Vec<_> = item.get("records").unwrap().as_array().unwrap().iter().map(record).collect();
    check(records.try_into().unwrap(), record(item.get("expected").unwrap()));
}

fn check(records: [Link; 3], expected: Link) {
    for [a, b, c] in [[0,1,2], [0,2,1], [1,0,2], [1,2,0], [2,0,1], [2,1,0]] {
        let left = try_merge(&try_merge(&records[a], &records[b]).unwrap(), &records[c]).unwrap();
        let right = try_merge(&records[a], &try_merge(&records[b], &records[c]).unwrap()).unwrap();
        assert_eq!(left, expected);
        assert_eq!(right, expected);
        assert_eq!(try_merge(&left, &records[a]).unwrap(), expected);
        assert_eq!(try_merge(&expected, &expected).unwrap(), expected);
    }
}
`;
const vectors = Object.entries(fixtures).map(([name, records]) => ({
  name,
  records,
  expected: merge(merge(records[0], records[1]), records[2]),
}));
for (const name of Object.keys(fixtures)) {
  output += `\n#[test]\nfn sync_reference_${name}() { fixture("${name}"); }\n`;
}
const data = await format(JSON.stringify(vectors), { parser: 'json' });
const fixtureFile = new URL(
  '../../rust/crates/meta-sovereign-core/tests/fixtures/sync-register.json',
  import.meta.url
);
// Keep generator output stable under the repository's Rust formatter.
const { spawnSync } = await import('node:child_process');
const formatted = spawnSync('rustfmt', ['--edition', '2024'], {
  input: output,
  encoding: 'utf8',
  maxBuffer: 1024 * 1024,
});
if (formatted.status !== 0) {
  throw new Error(`rustfmt failed: ${formatted.stderr}`);
}
const destination = fileURLToPath(
  new URL(
    '../../rust/crates/meta-sovereign-core/tests/sync_reference.rs',
    import.meta.url
  )
);
if (process.argv.includes('--check')) {
  if ((await readFile(fixtureFile, 'utf8')) !== data) {
    throw new Error('Native register input/expected fixture drift');
  }
  if ((await readFile(destination, 'utf8')) !== formatted.stdout) {
    throw new Error(
      'Native register expectations differ from the production JS reference'
    );
  }
} else if (resolve(process.argv[1] ?? '') === fileURLToPath(import.meta.url)) {
  await writeFile(destination, formatted.stdout);
  await writeFile(fixtureFile, data);
}
console.log(
  `Verified ${Object.keys(fixtures).length} finite JavaScript/native register fixtures`
);
