// Generate finite typed native expectations from the production JS register.
import { writeFile, readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import { merge } from '../../js/src/sync/register.js';
import { vcTick } from '../../js/src/sync/clock.js';

const link = (text, vc = {}, extra = {}) => ({
  id: 'shared',
  tokens: [text],
  children: [],
  vc,
  ...extra,
});
const original = [
  link('A', { a: 2 }, { children: ['z', 'a', 'z'] }),
  link('B', { b: 1 }, { children: ['b', 'a'] }),
  link('C', { a: 1, b: 1 }),
];
const joined = merge(original[0], original[1]);
const max = Number.MAX_SAFE_INTEGER;
const fixtures = {
  synthetic_clock: original,
  equal_clock: ['A', 'Z', 'B'].map((text) => link(text, { a: 1 })),
  zero_counter: [link('A', { a: 0 }), link('Z'), link('B', { b: 0 })],
  exact_sum: [
    link('Z', { a: max, b: max - 1 }),
    link('A', { a: max, b: max }),
    link('C', { c: max }),
  ],
  unicode_actor: [
    link('A', { '\u{10000}': 1 }),
    link('B', { '\ue000': 1 }),
    link('C', { z: 1 }),
  ],
  indexed_actor: [
    link('A', { 10: 1, 2: 1, z: 1 }),
    link('B', { 11: 1, 2: 1, z: 1 }),
    link('C', { 10: 1, 3: 1, z: 1 }),
  ],
  escaped_payload: ['\u0001', '\n', '"\\'].map((text) => link(text)),
  unicode_children: [
    link('A', {}, { children: ['\ue000', '\u{10000}', 'z'] }),
    link('B', {}, { children: ['\u{10000}', 'a'] }),
    link('C'),
  ],
  tick_width: ['9-z', '10-a', '00010-z'].map((version) =>
    link(version, {}, { version })
  ),
  huge_tick: ['legacy', '99999999999999999999999999999999-a', '9-z'].map(
    (version) => link(version, {}, { version })
  ),
  newline_version: ['10-a\n', '9-z', '10-a\u2028'].map((version) =>
    link(version, {}, { version })
  ),
  retained_assignment: [joined, original[2], original[1]],
  owner_edit: [
    { ...joined, tokens: ['owner edit'], vc: vcTick(joined.vc, 'a') },
    original[0],
    original[2],
  ],
};

const str = (value) =>
  `"${[...value]
    .map((c) =>
      c === '"' || c === '\\'
        ? `\\${c}`
        : c.codePointAt(0) < 32
          ? `\\u{${c.codePointAt(0).toString(16)}}`
          : c
    )
    .join('')}".into()`;
const array = (values) => `vec![${values.map(str).join(', ')}]`;
const clock = (value) =>
  `[${Object.entries(value)
    .map(([actor, n]) => `(${str(actor)}, ${n}u64)`)
    .join(', ')}].into_iter().collect()`;
const record = (value) => {
  const stamp = value.__msSyncStamp;
  return `Link { id: ${str(value.id)}, tokens: ${array(value.tokens)}, children: ${array(value.children)}, vc: ${clock(value.vc)}, sync_stamp: ${stamp ? `Some(AssignmentStamp { clock: ${clock(stamp.clock)}, context: ${clock(stamp.context)} })` : 'None'}, version: ${value.version === undefined ? 'None' : `Some(${str(value.version)})`} }`;
};

let output = `// Generated by experiments/issue-56/native-register-vectors.mjs.
// Expected records come from the production JavaScript implementation.
use meta_sovereign_core::{AssignmentStamp, Link, try_merge};

fn check(records: [Link; 3], expected: Link) {
    for [a, b, c] in [[0,1,2], [0,2,1], [1,0,2], [1,2,0], [2,0,1], [2,1,0]] {
        let left = try_merge(&try_merge(&records[a], &records[b]).unwrap(), &records[c]).unwrap();
        let right = try_merge(&records[a], &try_merge(&records[b], &records[c]).unwrap()).unwrap();
        assert_eq!(left, expected);
        assert_eq!(right, expected);
        assert_eq!(try_merge(&left, &records[a]).unwrap(), expected);
        assert_eq!(try_merge(&expected, &expected).unwrap(), expected);
    }
}
`;
for (const [name, records] of Object.entries(fixtures)) {
  const expected = merge(merge(records[0], records[1]), records[2]);
  output += `\n#[test]\nfn sync_reference_${name}() {\n    check([${records.map(record).join(', ')}], ${record(expected)});\n}\n`;
}
// Keep generator output stable under the repository's Rust formatter.
const { spawnSync } = await import('node:child_process');
const formatted = spawnSync('rustfmt', ['--edition', '2024'], {
  input: output,
  encoding: 'utf8',
  maxBuffer: 1024 * 1024,
});
if (formatted.status !== 0) {
  throw new Error(`rustfmt failed: ${formatted.stderr}`);
}
const destination = fileURLToPath(
  new URL(
    '../../rust/crates/meta-sovereign-core/tests/sync_reference.rs',
    import.meta.url
  )
);
if (process.argv.includes('--check')) {
  if ((await readFile(destination, 'utf8')) !== formatted.stdout) {
    throw new Error(
      'Native register expectations differ from the production JS reference'
    );
  }
} else if (resolve(process.argv[1] ?? '') === fileURLToPath(import.meta.url)) {
  await writeFile(destination, formatted.stdout);
}
console.log(
  `Verified ${Object.keys(fixtures).length} finite JavaScript/native register fixtures`
);
