q = lambda v: "'" + v.replace('\\', '\\\\').replace("'", "\\'") + "'"
root = sys.argv[1]
for loc, d in L.items():
    p = f'{root}/js/src/web/locales/{loc}.js'
    s = open(p).read()
    assert "'nav.reengage'" not in s
    lines = s.split('\n')
    i = next(n for n, l in enumerate(lines) if l.startswith("  'nav.outreach'"))
    lines.insert(i + 1, f"  'nav.reengage': {q(d['nav'])},")
    i = next(n for n, l in enumerate(lines) if l.startswith("  'guide.profile.title'"))
    lines[i:i] = [f"  'guide.reengage.title': {q(d['guide.title'])},",
                  f"  'guide.reengage.body': {q(d['guide.body'])},"]
    end = max(n for n, l in enumerate(lines) if l.strip() == '};')
    block = [f"  'reengage.{k}': {q(v)}," for k, v in d.items() if not k.startswith(('nav', 'guide.'))]
    lines[end:end] = block
    open(p, 'w').write('\n'.join(lines))
