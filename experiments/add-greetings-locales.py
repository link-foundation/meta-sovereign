def q(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'") + "'"

def entry(key, value):
    line = f"  {q(key)}: {q(value)},"
    if len(line) <= 80:
        return line + '\n'
    return f"  {q(key)}:\n    {q(value)},\n"

for lang, d in L.items():
    path = f'{ROOT}/js/src/web/locales/{lang}.js'
    s = open(path, encoding='utf-8').read()
    if "'nav.greetings'" in s:
        continue
    m = re.search(r"  'nav\.cv': .*\n", s)
    s = s[:m.end()] + entry('nav.greetings', d['nav']) + s[m.end():]
    m = re.search(r"  'guide\.cv\.body':\n.*\n", s)
    s = s[:m.end()] + entry('guide.greetings.title', d['guide.title']) + entry('guide.greetings.body', d['guide.body']) + s[m.end():]
    body = ''.join(entry(f'greetings.{k}', v) for k, v in d.items() if k not in ('nav', 'guide.title', 'guide.body'))
    end = s.rstrip().rfind('};')
    s = s[:end] + body + s[end:]
    open(path, 'w', encoding='utf-8').write(s)
    print(lang, 'ok')
