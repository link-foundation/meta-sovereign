// Builds js/src/web/emoji-data.js — the emoji panel's emoji (R-Y104) —
// from Unicode's emoji-test.txt (https://unicode.org/Public/emoji/latest/
// emoji-test.txt; © Unicode, Inc., Unicode License v3). Only
// fully-qualified emoji up to MAX_VERSION, so the system's fonts draw
// them all; the skin tones are left out of the lists (the panel shows the
// default yellow one) and only which emoji take a tone is kept
// (EMOJI_TONES, R-Y114). Telegram's apps put people with the
// smileys; the categories follow theirs.
//
//   node js/scripts/build-emoji-data.mjs path/to/emoji-test.txt

import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const MAX_VERSION = 15.0;
const GROUPS = {
  'Smileys & Emotion': 'people',
  'People & Body': 'people',
  'Animals & Nature': 'nature',
  'Food & Drink': 'food',
  Activities: 'activity',
  'Travel & Places': 'travel',
  Objects: 'objects',
  Symbols: 'symbols',
  Flags: 'flags',
};
const ORDER = [
  'people',
  'nature',
  'food',
  'activity',
  'travel',
  'objects',
  'symbols',
  'flags',
];
const SKIN = /[\u{1F3FB}-\u{1F3FF}]/u;

const source = process.argv[2];
if (!source) {
  console.error('usage: build-emoji-data.mjs <emoji-test.txt>');
  process.exit(1);
}
const text = await readFile(source, 'utf8');
const version = /^# Version: (.+)$/m.exec(text)?.[1] ?? '?';
const categories = new Map(ORDER.map((key) => [key, []]));
const everything = new Set();
const bases = [];
let group = null;
for (const line of text.split('\n')) {
  const head = /^# group: (.+)$/.exec(line);
  if (head) {
    group = GROUPS[head[1]] ?? null;
    continue;
  }
  const entry =
    /^[0-9A-F ]+;\s*fully-qualified\s*#\s*(\S+)\s+E(\d+\.\d+)\s+(.+)$/.exec(
      line
    );
  if (!group || !entry) {
    continue;
  }
  const [, emoji, since, name] = entry;
  if (Number(since) > MAX_VERSION) {
    continue;
  }
  everything.add(emoji);
  if (SKIN.test(emoji)) {
    continue;
  }
  bases.push(emoji);
  categories.get(group).push(`${emoji}~${name.replace(/[|~]/g, ' ')}`);
}

// The emoji with a one-tone form: the tone goes after the first code
// point (its FE0F dropped); kept only when Unicode lists that exact form.
const toned = (emoji) => {
  const [first, ...rest] = [...emoji];
  return [
    first,
    '\u{1F3FB}',
    ...(rest[0] === '\uFE0F' ? rest.slice(1) : rest),
  ].join('');
};
const tones = bases.filter((emoji) => everything.has(toned(emoji)));

const here = path.dirname(fileURLToPath(import.meta.url));
const target = path.join(here, '../src/web/emoji-data.js');
const body = ORDER.map(
  (key) => `  ${key}: ${JSON.stringify(categories.get(key).join('|'))},`
).join('\n');
await writeFile(
  target,
  `// Generated by js/scripts/build-emoji-data.mjs from Unicode's
// emoji-test.txt (version ${version}; © Unicode, Inc., Unicode License v3):
// emoji up to ${MAX_VERSION.toFixed(1)}, without skin tones, as "emoji~name|…" per
// category, and EMOJI_TONES: the ones that take a skin tone. Do not edit by
// hand.

export const EMOJI_CATEGORIES = {
${body}
};

export const EMOJI_TONES = ${JSON.stringify(tones.join('|'))};
`
);
const total = [...categories.values()].reduce((n, list) => n + list.length, 0);
console.log(`emoji-data.js: ${total} emoji, ${tones.length} with skin tones`);
