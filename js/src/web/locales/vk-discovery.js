export const vkDiscoveryLocale = (language) => {
  const translated = Object.fromEntries(
    keys.map((key, i) => [key, words[language][i]])
  );
  return Object.assign(
    {},
    ...discoveryKinds.map((kind) => {
      const prefix = `vk${kind[0].toUpperCase()}${kind.slice(1)}`;
      const title = `${kind[0].toUpperCase()}${kind.slice(1)}`;
      return {
        ...Object.fromEntries(
          Object.entries(vkGreetLocale(language)).map(([key, value]) => [
            `${prefix}.${key.slice(8)}`,
            value,
          ])
        ),
        ...Object.fromEntries(
          Object.entries(translated).map(([key, value]) => [
            `${prefix}.${key}`,
            value,
          ])
        ),
        [`${prefix}.title`]: translated[`title${title}`],
        [`${prefix}.hint`]: translated[`hint${title}`],
      };
    })
  );
};
